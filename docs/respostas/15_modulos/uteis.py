"""Funções utilitárias importadas pelo main.py."""


def media(lista):
    """Retorna a média aritmética dos valores da lista."""
    return sum(lista) / len(lista)


def maior(lista):
    """Retorna o maior valor da lista."""
    return max(lista)


def menor(lista):
    """Retorna o menor valor da lista."""
    return min(lista)
